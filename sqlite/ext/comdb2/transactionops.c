#include <stdlib.h>
#include <string.h>
#include <stddef.h>
#include "comdb2.h"
#include "comdb2systblInt.h"
#include "ezsystables.h"
#include "comdb2uuid.h"
#include "osqlsession.h"
#include "osqlrepository.h"

/* One row per (transaction, table, opcode) of the transactions the master is
 * building or applying; opcodes are the osql ops saved to the bplog, plus the
 * FK_* rows generated by foreign key actions. */
typedef struct systable_txnop {
    char *uuid;
    char *tablename;
    char *opcode;
    int64_t count;
    char *identity;
    int64_t start_time;
} systable_txnop_t;

typedef struct get_txnops {
    int count;
    int alloc;
    systable_txnop_t *records;
} get_txnops_t;

static int collect_op_count(osql_sess_t *sess, const char *identity, const osql_sess_op_count_t *c, void *arg)
{
    get_txnops_t *ops = arg;
    uuidstr_t us;

    if (ops->count >= ops->alloc) {
        ops->alloc = ops->alloc ? ops->alloc * 2 : 128;
        ops->records = realloc(ops->records, ops->alloc * sizeof(systable_txnop_t));
    }
    systable_txnop_t *o = &ops->records[ops->count++];
    o->uuid = strdup(comdb2uuidstr(sess->uuid, us));
    o->tablename = c->table ? strdup(c->table) : NULL;
    o->opcode = strdup(c->opcode);
    o->count = c->count;
    o->identity = identity ? strdup(identity) : NULL;
    o->start_time = sess->sess_startus / 1000; /* ms since the epoch */
    return 0;
}

static int collect_session(void *obj, void *arg)
{
    osql_sess_for_each_op_count(obj, arg, collect_op_count);
    return 0;
}

static int get_txnops(void **data, int *records)
{
    get_txnops_t ops = {0};
    osql_repository_for_each(&ops, collect_session);
    *data = ops.records;
    *records = ops.count;
    return 0;
}

static void free_txnops(void *p, int n)
{
    systable_txnop_t *t = p;
    for (int i = 0; i < n; i++) {
        free(t[i].uuid);
        free(t[i].tablename);
        free(t[i].opcode);
        free(t[i].identity);
    }
    free(p);
}

sqlite3_module systblTransactionOpsModule = {
    .access_flag = CDB2_ALLOW_USER | CDB2_STRICT,
};

int systblTransactionOpsInit(sqlite3 *db)
{
    return create_system_table(
        db, "comdb2_transaction_ops", &systblTransactionOpsModule,
        get_txnops, free_txnops, sizeof(systable_txnop_t),
        CDB2_CSTRING, "uuid", -1, offsetof(systable_txnop_t, uuid),
        CDB2_CSTRING, "tablename", -1, offsetof(systable_txnop_t, tablename),
        CDB2_CSTRING, "opcode", -1, offsetof(systable_txnop_t, opcode),
        CDB2_INTEGER, "count", -1, offsetof(systable_txnop_t, count),
        CDB2_CSTRING, "identity", -1, offsetof(systable_txnop_t, identity),
        CDB2_INTEGER, "start_time", -1, offsetof(systable_txnop_t, start_time),
        SYSTABLE_END_OF_FIELDS);
}
